"""
Phase 6: Guardrails - the difference between a demo and a production agent.

Here, the guardrails implements a strict manual safety checks apart from the AI decision. Say, though AI is
very confident and wanted to send/delete an email by having a good threshold say 0.85, the guardrail would 
reject it seeing through the manual evaluation it has done.

LLMs are confident even when they are wrong. Confidence score from LLM can be a starting signal (consider, if the
LLM is saying that I'm 90% confident in sending this email then that's the rough estimate generated by the model)
but not a ground truth. So, guardrails also apply hard rules that don't depend on the model grading it's own 
homework. These guardrails are acted as an escalation but not a failure. When it is unsure, the agent should NOT
silently do nothing or silently do act something. Rather, it should label the task for human to review and log
why this diversion for human review has happened.

DRY-RUN: It is safe by design, built into the architecture right from the beginning and zero fear experimentation.
Basically, this switches to the simulation mode which is same as the live production say fetching the real emails,
runs them through the LLM classification, triggers the guardrails and maps out the decision.
"""

import os
import re

DRY_RUN = os.getenv("DRY_RUN", "true").lower() == "true"
CONFIDENCE_THRESHOLD = float(os.getenv("CONFIDENCE_THRESHOLD", "0.75"))

"""
Hard rules that you define in your guardrails implementation override model confidence entirely -- these catches the
cases where the model might be confidently wrong.
"""

SENSITIVE_PATTERNS = [
    # 1. Legal and Liability
    r"\blegal\b",
    r"\blawsuit\b",
    r"\bcontract\b",
    
    # 2. Financial Transactions & Fraud
    r"\binvoice\b",
    r"\bwire transfer\b",
    r"\bcredit card\b",
    r"\bcvv\b",
    r"\brouting number\b",
    r"\bbitcoin\b",
    r"\bchargeback\b",
    r"\brefund\b",
    
    # 3. Security Credentials & Secrets
    r"\bpassword\b",
    r"\bapi[_\s]?key\b",
    r"\bsecret[_\s]?key\b",
    r"\btoken\b",
    r"\botp\b",
    r"\bverification code\b",
    
    # 4. Personal Identifiable Information (PII)
    r"\bssn\b",
    r"\bsocial security\b",
    
    # 5. HR & Corporate Confidentiality
    r"\btermination\b",
    r"\bresignation\b",
    r"\blayoff\b",
    r"\bsalary\b",
    r"\bmedical\b",
    r"\bhipaa\b",
    
    # 6. Phishing & Aggressive Lures
    r"\breset[_\s]?password\b",
    r"\bverify[_\s]?your[_\s]?account\b",
    r"\bunsubscribe\b.*\bimmediately\b",
]

def is_sensitive_content(subject: str, body: str) -> bool:
    text = f"{subject} {body}".lower()
    return any(re.search(p, text) for p in SENSITIVE_PATTERNS)

def evaluate(action: str, confidence: float, subject: str, body: str) -> tuple[bool, str]:
    """
    Returns (approved: bool, reason: str).

    This is called BEFORE act_node executes anything. It is the single chokepoint every destructive action must pass
    through -- put new safety rules here, not scattered through the graph.
    """

    # Read-only / non-destructive actions always pass
    if action in ("label", "ignore", "draft"):
        return True, "Non-destructive action, no gate needed."
    
    if DRY_RUN:
        return False, "DRY_RUN is enabled -- all send/archive actions are simulated, not executed."
    
    if is_sensitive_content(subject, body):
        return False, "Content matches a sensitive pattern (legal/financial/credentials) -- escalating to human review."
    
    if confidence < CONFIDENCE_THRESHOLD:
        return False, f"Confidence {confidence:.2f} below threshold {CONFIDENCE_THRESHOLD} -- escalating."
    
    return True, f"Passed guardrails (confidence {confidence:.2f}, no sensitive patterns)."